    public void PreencherTabelaProcesso(String SQL) {

        ArrayList dados = new ArrayList();
        String[] colunas = new String[]{"ID","HOST", "DB"};
        connUpdate.executaSQL(SQL);
        try {
            connUpdate.rs.first();
            do {
                dados.add(new Object[]{connUpdate.rs.getInt("ID"),connUpdate.rs.getString("HOST"), connUpdate.rs.getString("DB")});
            } while (connUpdate.rs.next());
        } catch (Exception e) {
            //JOptionPane.showMessageDialog(null, "Erro ao preencher o ArrayList de produtos \n ERRO:" + e);
            JOptionPane.showMessageDialog(null, "Erro ao preencher ArrayList de processos \nERRO:"+e);
        }
        ModeloTabela modelo = new ModeloTabela(dados, colunas);
        jTableProcess.setModel(modelo);
        jTableProcess.getColumnModel().getColumn(0).setPreferredWidth(50);//Código
        jTableProcess.getColumnModel().getColumn(0).setResizable(false);
        jTableProcess.getColumnModel().getColumn(1).setPreferredWidth(187);//Descrição do Produto
        jTableProcess.getColumnModel().getColumn(1).setResizable(false);
        jTableProcess.getColumnModel().getColumn(2).setPreferredWidth(100);//Preço
        jTableProcess.getColumnModel().getColumn(2).setResizable(false);
        jTableProcess.setAutoResizeMode(jTableProcess.AUTO_RESIZE_OFF);
        jTableProcess.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
    }
