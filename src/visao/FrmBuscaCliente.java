public void preencherTabelaCliente(String SQL) {
        ArrayList dados = new ArrayList();
        String[] colunas = new String[]{"Código", "Nome", "cpf"};
        connCliente.executaSQL(SQL);
        try {
            connCliente.rs.first();
            do {
                dados.add(new Object[]{connCliente.rs.getInt("codcliente"), connCliente.rs.getString("cliente"), connCliente.rs.getString("cpf")});
            } while (connCliente.rs.next());
            connCliente.desconectar();
        } catch (SQLException ex) {
            //JOptionPane.showMessageDialog(null, "Erro ao preencher o ArrayList de Clientes\n ERRO:" + ex);
            JOptionPane.showMessageDialog(null, "Cliente não encontrado");
            txtBuscaCli.setText("");
        }
        ModeloTabela modelo = new ModeloTabela(dados, colunas);
        jTableBuscaCli.setModel(modelo);
        jTableBuscaCli.getColumnModel().getColumn(0).setPreferredWidth(80);
        jTableBuscaCli.getColumnModel().getColumn(0).setResizable(false);
        jTableBuscaCli.getColumnModel().getColumn(1).setPreferredWidth(193);
        jTableBuscaCli.getColumnModel().getColumn(1).setResizable(false);
        jTableBuscaCli.getColumnModel().getColumn(2).setPreferredWidth(100);
        jTableBuscaCli.getColumnModel().getColumn(2).setResizable(false);
        jTableBuscaCli.getTableHeader().setReorderingAllowed(false);
        jTableBuscaCli.setAutoResizeMode(jTableBuscaCli.AUTO_RESIZE_OFF);
        jTableBuscaCli.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        connCliente.desconectar();
    }   
