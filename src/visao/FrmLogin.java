    private void validaLicenca(String id) {
        try {
            conn.executaSQL("select * from vencimento");
            conn.rs.last();
            //pega a data do dia e coloca no formato dd/mm/yyyy
            SimpleDateFormat df = new SimpleDateFormat("dd/MM/yyyy");
            Date hoje = new Date();
            String dataHoje = (String) df.format(hoje);

            //data do banco
//            String dataSistema = conn.rs.getString("data_venc");
            char[] dataMostra = conn.rs.getString("datavenc").toCharArray();
            String dataMostra2 = String.valueOf(dataMostra[0] + "" + dataMostra[1] + "" + dataMostra[2] + "" + dataMostra[3] + "" + dataMostra[4] + "" + dataMostra[5] + "" + dataMostra[6] + "" + dataMostra[7] + "" + dataMostra[8] + "" + dataMostra[9] + "" + dataMostra[10] + "" + dataMostra[11]);
            System.out.println("dataMostra(base64) " + dataMostra2);

            //Decodifica o hash da data de vencimento
            byte[] decodificaProxdata = Base64.getDecoder().decode(dataMostra2);
            String dataDecodificada = new String(decodificaProxdata);
            //Monta a data decodificada para o padrão DD/MM/YYYY
            String dia = dataDecodificada.substring(0, 2);
            String mes = dataDecodificada.substring(2, 4);
            String ano = dataDecodificada.substring(4, 8);
            String dataSisModificada = dia + "/" + mes + "/" + ano;

            System.out.println("dataSisModificada(ajeitada para o padrão dd/mm/yyyy) " + dataSisModificada);
            System.out.println("dataSis (Decodificada do base64) " + dataDecodificada);
            String dthash = conn.rs.getString("sec");
            System.out.println("campo sec do banco " + dthash);

            //pega a variavel dataMostra e transforma em md5 para fazer a comparação
            String datamostrahash = HashMd5.HashMd5(dataMostra2);
            System.out.println("data base64 transformada em md5 " + datamostrahash);
            conn.desconectar();
            try {
                Date dtHoje = df.parse(dataHoje);
                Date dtSistema = df.parse(dataSisModificada);
                //Verifica se o hash da data mudou
                if (dthash.compareTo(datamostrahash) != 0) {
                    JOptionPane.showMessageDialog(null, "O sistema está bloquedo! \n Provavelmente ocorreu algum erro com a data de vencimento. Por favor entre com contato com o suporte tecnico!", "ERRO", JOptionPane.ERROR_MESSAGE);
                    btnEntrar.setEnabled(false);
                    conn.desconectar();
                } else if ((dtHoje.compareTo(dtSistema) < 0)) {
                    //se a data é menor
                    FrmPrincipal cad_princ = new FrmPrincipal(id, txtUsuario.getText(), jLabelVersao.getText());
                    cad_princ.setVisible(true);
                    conn.desconectar();
                    this.dispose();
                } else if (dtHoje.compareTo(dtSistema) > 0) {
                    //se a data é maior
                    FrmValidarSistema validar = new FrmValidarSistema();
                    validar.setVisible(true);
                    btnEntrar.setEnabled(false);
                    conn.desconectar();
                    this.dispose();  
                } else if (dtHoje.compareTo(dtSistema) == 0) {
                    //se a data é igual
                    FrmPrincipal cad_princ = new FrmPrincipal(id, txtUsuario.getText(), jLabelVersao.getText());
                    cad_princ.setVisible(true);
                    System.out.println("HASH IGUAL");
                    conn.desconectar();
                    this.dispose();
                }
                conn.desconectar();
            } catch (ParseException ex) {
                Logger.getLogger(FrmLogin.class.getName()).log(Level.SEVERE, null, ex);
                System.out.println("dataSis" + dataDecodificada);
                conn.desconectar();
            }
            conn.desconectar();
        } catch (SQLException ex) {
            Logger.getLogger(FrmLogin.class.getName()).log(Level.SEVERE, null, ex);
            conn.desconectar();
        }
        conn.desconectar();
    }
