    public void dataLoginDb() {
        try {
            conn.executaSQL("select * from datalogin");
            conn.rs.last();
            if (!conn.rs.last()) {
                JOptionPane.showMessageDialog(null, "CÓDIGO DO ERRO: ACC03 \nAlterações no Banco de dados geram inconsistencias no sistema! \nEntre com contato com o suporte técnico informando que a data do login no sistema foi excluído do banco de dados", "\nERRO: Alteração em banco", JOptionPane.ERROR_MESSAGE);
                btnEntrar.setEnabled(false);
                conn.desconectar();
            } else {
                SimpleDateFormat df = new SimpleDateFormat("dd/MM/yyyy");
                Date hoje = new Date();
                String dtHoje = (String) df.format(hoje);
                String dia = dtHoje.substring(0, 2);
                String mes = dtHoje.substring(3, 5);
                String ano = dtHoje.substring(6);
                String dataParaMysql = ano + "-" + mes + "-" + dia;
                String dataParaMysqlEncode = Base64.getEncoder().encodeToString(dataParaMysql.getBytes());
                String dataBancoEncoded = conn.rs.getString("datalogin");
                System.out.println("Data do windows: " + dataParaMysql + "\nData do banco(login)" + dataBancoEncoded+"ENCODE "+dataParaMysqlEncode);

                byte[] dataMysqlDecode = Base64.getDecoder().decode(dataBancoEncoded);//TESTAR AQYU
                String dataBancoDecoded = new String(dataMysqlDecode);
                //Se a data do windows for menor que a do ultimo login
                if (dataParaMysql.compareTo(dataBancoDecoded) < 0) {
                    FrmValidarSistema valida = new FrmValidarSistema();
                    valida.setVisible(true);
                    btnEntrar.setEnabled(false);
                    JOptionPane.showMessageDialog(rootPane, "CÓDIGO DO ERRO: ACC05\nVerifique a data do sistema operacional!");
                    valida.toFront();
                    conn.desconectar();
                } else {
                    conn.conectar();
                    control.DeletarDtLogin(mod, conn);
                    mod.setDtLogin(dataParaMysqlEncode);
                    control.InserirDtLogin(mod, conn);
                    System.out.println("nova data de login: " + dataParaMysql + " Nova data de login ENcoded: " + dataParaMysqlEncode);
                    conn.desconectar();
                }
                conn.desconectar();
            }
            conn.desconectar();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "CÓDIGO DO ERRO: ACC04 \nAlterações no Banco de dados geram inconsistencias no sistema! \nEntre com contato com o suporte técnico informando que a data do login no sistema foi excluído do banco de dados", "\nERRO: Alteração em banco", JOptionPane.ERROR_MESSAGE);
            btnEntrar.setEnabled(false);
            conn.desconectar();
        }
        conn.desconectar();
    }

    /*Função que verifica se o dia do ultimo login é maior que a data */
    public void verificaDia() {
        try {
            conn.executaSQL("select * from datalogin");
            conn.rs.last();

            SimpleDateFormat df = new SimpleDateFormat("dd/MM/yyyy");
            Date hoje = new Date();
            String dataHoje = (String) df.format(hoje);
            String dataLoginDB = conn.rs.getString("datalogin");
            byte[] dataloginEncoded = Base64.getDecoder().decode(dataLoginDB);
            String dataLogin = new String(dataloginEncoded);
            String dia = dataLogin.substring(0, 4);
            String mes = dataLogin.substring(5, 7);
            String ano = dataLogin.substring(8, 10);
            String dataSisModificada = ano + "/" + mes + "/" + dia;

            try {
                Date dtHoje = df.parse(dataHoje);
                Date dtSistema = df.parse(dataSisModificada);
                if (dtHoje.compareTo(dtSistema) < 0) {
                    //Se a data for menor
                    FrmValidarSistema validar = new FrmValidarSistema();
                    validar.setVisible(true);
                    conn.desconectar();
                    this.dispose();
                } else if (dtHoje.compareTo(dtSistema) >= 0) {
                    //Se a data for maior ou igual
                    entrar();
                    conn.desconectar();
                }
            } catch (ParseException e) {
                JOptionPane.showMessageDialog(rootPane, "Erro: " + e);
            }
            conn.desconectar();
        } catch (SQLException ex) {
            Logger.getLogger(FrmLogin.class.getName()).log(Level.SEVERE, null, ex);
            conn.desconectar();
        }
    }

