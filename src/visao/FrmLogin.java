    public void entrar() {
        try {
            String codid = "";
            conn.stmt = conn.connection.createStatement(conn.rs.TYPE_SCROLL_INSENSITIVE, conn.rs.CONCUR_READ_ONLY);
            conn.rs = conn.stmt.executeQuery("select * from usuario where login='" + txtUsuario.getText() + "'");
            conn.rs.next();
            System.out.println("entrar " + conn);
            if (txtUsuario.getText().equals("") || txtSenha.getText().equals("")) {
                JOptionPane.showMessageDialog(null, "Campo Vazio");
                txtSenha.setText("");
            } else if (conn.rs.getString("bloqueado").equals("S")) {
                JOptionPane.showMessageDialog(null, "Usuario bloqueado, contate o administrador do sistema!");
            } else if (conn.rs.getString("senha").equals(txtSenha.getText())) {
                codid = conn.rs.getString("codusuario");
                validaLicenca(codid);
//                FrmPrincipal principal = new FrmPrincipal(txtUsuario.getText());
//                principal.setVisible(true);
                conn.desconectar();
            } else {
                JOptionPane.showMessageDialog(rootPane, "Usuário ou Senha incorretos!");
                txtSenha.setText("");
                conn.desconectar();
            }
            conn.desconectar();
        } catch (SQLException | HeadlessException e) {
            JOptionPane.showMessageDialog(rootPane, "Usuário ou Senha incorretos!");
            txtSenha.setText("");
            conn.desconectar();
        }
    }

