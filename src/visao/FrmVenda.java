    private void btnNovoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNovoActionPerformed
        try {
            //connVenda.conectar();
            //connVenda.executaSQL("START TRANSACTION");
            connVenda.executaSQL("SELECT proxnumvenda FROM parametro FOR UPDATE");
            connVenda.rs.next();
            String result = connVenda.rs.getString("proxnumvenda");
            txtIdVenda.setText(result);
            PreparedStatement pstm = connVenda.connection.prepareStatement("UPDATE parametro SET proxnumvenda=proxnumvenda+1");
            pstm.execute();
            PreparedStatement pstm2 = connVenda.connection.prepareStatement("COMMIT");
            pstm2.execute();
            //Insere na tabela cad_venda o id da venda 
            PreparedStatement pstm3 = connVenda.connection.prepareStatement("INSERT INTO pedido (numvenda,dtvenda) VALUES ('" + txtIdVenda.getText() + "',NOW())");
            pstm3.execute();
            connVenda.desconectar();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Erro ao iniciar venda!" + e);

            try {
                connVenda.conectar();
                PreparedStatement pstm4 = connVenda.connection.prepareStatement("UPDATE parametro SET proxnumvenda=proxnumvenda-1");
                pstm4.execute();
                connVenda.desconectar();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(rootPane, "Erro ao voltar numero da venda!" + ex);
            }

        }
        btnNovo.setEnabled(false);
        btnSalvar.setEnabled(false);
        btnCancelar.setEnabled(true);
        btnAlterar.setEnabled(false);
        //jTableOrcamento.setVisible(false);
        //txtNomeUsuario.requestFocus();
        //cbPermissao.setEnabled(true);
        libera_campos();
        limpa_campos();
        connVenda.desconectar();
    }//GEN-LAST:event_btnNovoActionPerformed

