    public void preencherTabelaVenda(String SQL) {
        //connVenda.conectar();
        ArrayList dados = new ArrayList();
        String[] colunas = new String[]{"Num. Venda", "Cod. Prod", "Descrição", "Quantidade", "Preço", "Valor dos produtos"};
        //String[] colunas = new String[]{"Num. Venda"};
        connVenda.executaSQL(SQL);
        try {
            connVenda.rs.first();
            do {
                dados.add(new Object[]{connVenda.rs.getInt("numvenda"), connVenda.rs.getInt("codprod"), connVenda.rs.getString("descricao"), connVenda.rs.getDouble("qtde"), connVenda.rs.getDouble("preco"), connVenda.rs.getDouble("vlitem")});
                //dados.add(new Object[]{connVenda.rs.getInt("pedido.numvenda")});
                //connVenda.desconectar();
            } while (connVenda.rs.next());
            connVenda.desconectar();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Erro ao preencher o ArrayList de produtos\n ERRO:" + ex + "\nERRO: \n" + SQL);
        }
        ModeloTabela modelo = new ModeloTabela(dados, colunas);
        jTableOrcamento.setModel(modelo);
        jTableOrcamento.getColumnModel().getColumn(0).setPreferredWidth(80);//numvenda
        jTableOrcamento.getColumnModel().getColumn(0).setResizable(false);//numvenda
        jTableOrcamento.getColumnModel().getColumn(1).setPreferredWidth(80);//codprod
        jTableOrcamento.getColumnModel().getColumn(1).setResizable(false);//codprod
        jTableOrcamento.getColumnModel().getColumn(2).setPreferredWidth(200);
        jTableOrcamento.getColumnModel().getColumn(2).setResizable(false);
        jTableOrcamento.getColumnModel().getColumn(3).setPreferredWidth(80);
        jTableOrcamento.getColumnModel().getColumn(3).setResizable(false);
        jTableOrcamento.getColumnModel().getColumn(4).setPreferredWidth(80);
        jTableOrcamento.getColumnModel().getColumn(4).setResizable(false);
        jTableOrcamento.getColumnModel().getColumn(5).setPreferredWidth(150);
        jTableOrcamento.getColumnModel().getColumn(5).setResizable(false);
        jTableOrcamento.getTableHeader().setReorderingAllowed(false);
        jTableOrcamento.setAutoResizeMode(jTableOrcamento.AUTO_RESIZE_OFF);
        jTableOrcamento.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        connVenda.desconectar();
    }

