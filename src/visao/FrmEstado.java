    public void preencherTabelaEstado(String SQL) {
        ArrayList dados = new ArrayList();
        String[] colunas = new String[]{"Código Estado", "Estado", "sigla"};
        connEstado.executaSQL(SQL);
        try {
            connEstado.rs.first();
            do {
                dados.add(new Object[]{connEstado.rs.getInt("codestado"), connEstado.rs.getString("estado"), connEstado.rs.getString("sigla")});
            } while (connEstado.rs.next());
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Erro ao preencher o ArrayList estado\n ERRO:" + ex);
        }
        ModeloTabela modelo = new ModeloTabela(dados, colunas);
        jTableEstado.setModel(modelo);
        jTableEstado.getColumnModel().getColumn(0).setPreferredWidth(100);
        jTableEstado.getColumnModel().getColumn(0).setResizable(false);
        jTableEstado.getColumnModel().getColumn(1).setPreferredWidth(293);
        jTableEstado.getColumnModel().getColumn(1).setResizable(false);
        jTableEstado.getColumnModel().getColumn(2).setPreferredWidth(290);
        jTableEstado.getColumnModel().getColumn(2).setResizable(false);
        jTableEstado.getTableHeader().setReorderingAllowed(false);
        jTableEstado.setAutoResizeMode(jTableEstado.AUTO_RESIZE_OFF);
        jTableEstado.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
    }

