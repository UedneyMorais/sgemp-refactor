    public void PreencherTabelaCompra(String SQL) {

        ArrayList dados = new ArrayList();
        String[] colunas = new String[]{"Código", "Data", "Produto", "Valor", "Qtde", "Fornecedor", "Engradado"};
        connProduto.executaSQL(SQL);
        try {
            connProduto.rs.first();
            FormatoData dataFormatada = new FormatoData();
            do {
                dados.add(new Object[]{connProduto.rs.getInt("id_compra"), dataFormatada.getDataBR(connProduto.rs.getDate("data_compra")), connProduto.rs.getString("desc_prod"), connProduto.rs.getString("valor_prod"), connProduto.rs.getString("qtde_compra"), connProduto.rs.getString("nome_fornec"), connProduto.rs.getString("engradado_compra")});
            } while (connProduto.rs.next());
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Erro ao preencher o ArrayList de compras \n ERRO:" + e);
            //txtBuscaProd.setText("");
        }
        ModeloTabela modelo = new ModeloTabela(dados, colunas);
        jTableCompra.setModel(modelo);
        jTableCompra.getColumnModel().getColumn(0).setPreferredWidth(50);//Código
        jTableCompra.getColumnModel().getColumn(0).setResizable(false);
        jTableCompra.getColumnModel().getColumn(1).setPreferredWidth(80);//Data
        jTableCompra.getColumnModel().getColumn(1).setResizable(false);
        jTableCompra.getColumnModel().getColumn(2).setPreferredWidth(200);//Produto
        jTableCompra.getColumnModel().getColumn(2).setResizable(false);
        jTableCompra.getColumnModel().getColumn(3).setPreferredWidth(60);//Valor compra
        jTableCompra.getColumnModel().getColumn(3).setResizable(false);
        jTableCompra.getColumnModel().getColumn(4).setPreferredWidth(42);//Qtde
        jTableCompra.getColumnModel().getColumn(4).setResizable(false);
        jTableCompra.getColumnModel().getColumn(5).setPreferredWidth(200);//Fornecedor
        jTableCompra.getColumnModel().getColumn(5).setResizable(false);
        jTableCompra.getColumnModel().getColumn(6).setPreferredWidth(80);//Engradado
        jTableCompra.getColumnModel().getColumn(6).setResizable(false);
        jTableCompra.getTableHeader().setReorderingAllowed(false);
        jTableCompra.setAutoResizeMode(JTable.AUTO_RESIZE_OFF);
        jTableCompra.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
    }

    public void botao() {
        btnNovo.setEnabled(true);
        btnAlterar.setEnabled(true);
        btnAtualizar.setEnabled(false);
        btnExcluir.setEnabled(true);
        btnCancelar.setEnabled(false);
        btnSalvar.setEnabled(false);
    }

    public void libera_campos() {
        txtDataFormatada.setEnabled(true);
        cbProduto.setEnabled(true);
        cbFornecedor.setEnabled(true);
        txtQtde.setEnabled(true);
        txtValor.setEnabled(true);
        txtEngradado.setEnabled(true);
    }

