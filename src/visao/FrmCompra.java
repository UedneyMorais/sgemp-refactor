    public FrmCompra() {
        initComponents();
        this.setIconImage(new ImageIcon(getClass().getResource("/imagens/icone.png")).getImage());
        bloqueia_campos();
        botao();
        try {
            MaskFormatter form = new MaskFormatter("##/##/####");
            txtDataFormatada.setFormatterFactory(new DefaultFormatterFactory(form));
            
        } catch (Exception e) {
        }
        PreencherTabelaCompra("SELECT id_compra,data_compra,cad_prod.desc_prod,cad_compra.valor_prod,qtde_compra,cad_fornec.nome_fornec,engradado_compra \n"
                + "FROM cad_compra\n"
                + "INNER JOIN cad_fornec ON cad_compra.id_fornec = cad_fornec.id_fornec\n"
                + "INNER JOIN cad_prod ON cad_compra.id_prod = cad_prod.id_prod");
        connProduto.conectar();
        connProduto.executaSQL("SELECT * FROM CAD_PROD ORDER BY DESC_PROD");
        cbProduto.removeAllItems();
        try {
            connProduto.rs.first();
            do {
                cbProduto.addItem(connProduto.rs.getString("desc_prod"));
            } while (connProduto.rs.next());
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(rootPane, "Erro ao preencher o combo box com produtos \n ERRO: " + ex);
        }

        connFornecedor.executaSQL("select * from cad_fornec order by nome_fornec");
        cbFornecedor.removeAllItems();
        try {
            connFornecedor.rs.first();
            do {
                cbFornecedor.addItem(connFornecedor.rs.getString("nome_fornec"));
            } while (connFornecedor.rs.next());
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(rootPane, "Erro ao preencher o combo box com fornecedores \n ERRO: " + ex);
        }
    }

