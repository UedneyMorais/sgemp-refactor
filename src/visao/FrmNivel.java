    public FrmNivel(String user) {
        initComponents();
        recebeUser(user);
        String sql = "SELECT * FROM usuario INNER JOIN frame ON usuario.codframe = frame.codframe AND codusuario='" + user + "'";
        this.setIconImage(new ImageIcon(getClass().getResource("/imagens/icone.png")).getImage());
        preencherTabelaFrame(sql);
        botao();
        bloqueia_campos();
        try {
            limpaCb();
            connNivel.conectar();
            connNivel.executaSQL(sql);
            connNivel.rs.next();
            do {
                this.codFrame = Integer.parseInt(connNivel.rs.getString("codframe"));
                cbBackup.addItem(connNivel.rs.getString("frmBackup"));
                cbCidade.addItem(connNivel.rs.getString("frmCidade"));
                cbClientes.addItem(connNivel.rs.getString("frmCliente"));
                cbCompra.addItem(connNivel.rs.getString("frmCompra"));
                cbContasPG.addItem(connNivel.rs.getString("frmContaspg"));
                cbEstado.addItem(connNivel.rs.getString("frmEstado"));
                cbForcec.addItem(connNivel.rs.getString("frmFornecedor"));
                cbNivel.addItem(connNivel.rs.getString("frmNivel"));
                cbOrcam.addItem(connNivel.rs.getString("frmOrcamento"));
                cbPedidos.addItem(connNivel.rs.getString("frmPedido"));
                cbPesqCli.addItem(connNivel.rs.getString("frmPesquisaCli"));
                cbUsuarios.addItem(connNivel.rs.getString("frmUsuario"));
                cbprod.addItem(connNivel.rs.getString("frmProduto"));
                cbvenda.addItem(connNivel.rs.getString("frmVenda"));
            } while (connNivel.rs.next());
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(null, "Erro ao preencher o combo box com permissões!\n ERRO: " + ex, "ERRO", JOptionPane.ERROR_MESSAGE);
        
        }
       
    }

