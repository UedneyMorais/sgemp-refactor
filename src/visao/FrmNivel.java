    public void recebeUser(String user) {
        try {
            connNivel.conectar();
            connNivel.executaSQL("SELECT * FROM usuario INNER JOIN frame ON usuario.codframe = frame.codframe AND codusuario='" + user + "'");
            connNivel.rs.next();
            txtCod.setText(connNivel.rs.getString("codusuario"));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(cbprod, "Erro ao buscar o id do frame \nERRO: " + e + "ERRO" + JOptionPane.ERROR_MESSAGE);
        }

    }
    
