        jTableNivel.getColumnModel().getColumn(5).setResizable(false);
        jTableNivel.getColumnModel().getColumn(6).setPreferredWidth(100);
        jTableNivel.getColumnModel().getColumn(6).setResizable(false);
        jTableNivel.getColumnModel().getColumn(7).setPreferredWidth(100);
