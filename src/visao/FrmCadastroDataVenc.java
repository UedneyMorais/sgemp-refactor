    private void btnGravarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGravarActionPerformed
        // TODO add your handling code here:

        try {
            conn.conectar();
            conn.executaSQL("select * from vencimento where dtvenc ='"+txtDataVenc.getText()+"'");
            conn.rs.next();
            if (conn.rs.next()){
                JOptionPane.showMessageDialog(rootPane, "Data já cadastrada!");
            } else {
                mod.setData(txtDataVenc.getText());
                control.SalvarData(mod.getData());
                dispose();
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(rootPane,"Erro ao gravar a data\nERRO:"+ ex);
        }
    }//GEN-LAST:event_btnGravarActionPerformed

